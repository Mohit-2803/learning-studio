function isSafeDbName(name: string): boolean {
  return /^[a-z][a-z0-9_]{0,30}$/.test(name);
}

function toUserSchema(name: string): string {
  return `${USER_SCHEMA_PREFIX}${name}`;
}

function fromUserSchema(schema: string): string | null {
  if (!schema.startsWith(USER_SCHEMA_PREFIX)) return null;
  return schema.slice(USER_SCHEMA_PREFIX.length);
}

function quoteIdent(identifier: string): string {
  return `"${identifier.replace(/"/g, '""')}"`;
}

function sqlLiteral(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

/**
 * Practice DBs are schemas inside one PGlite engine, so Postgres' real
 * current_database() is always "postgres". Rewrite the common teaching
 * helper so learners see the name of the DB chip they selected.
 */
function rewritePracticeSql(sql: string, practiceDbName: string): string {
  return sql.replace(
    /\bcurrent_database\s*\(\s*\)/gi,
    `CAST(${sqlLiteral(practiceDbName)} AS text)`,
  );
}

async function applyPracticeDbContext(client: PGliteClient, target: WorkspaceDb) {
  await client.exec(`SET search_path TO ${quoteIdent(target.schema)}, public`);
  // Custom GUC for anything that wants the logical name without rewrite.
  await client.exec(
    `SELECT set_config('learning.practice_db', ${sqlLiteral(target.name)}, false)`,
  );
}

function splitStatements(sql: string): string[] {
  const statements: string[] = [];
  let current = "";
  let inSingle = false;
  let inDouble = false;
  let inLineComment = false;
  let inBlockComment = false;

  for (let i = 0; i < sql.length; i += 1) {
    const ch = sql[i];
    const next = sql[i + 1];

    if (inLineComment) {
      current += ch;
      if (ch === "\n") inLineComment = false;
      continue;
    }
    if (inBlockComment) {
      current += ch;
      if (ch === "*" && next === "/") {
        current += "/";
        i += 1;
        inBlockComment = false;
      }
      continue;
    }
    if (inSingle) {
      current += ch;
      if (ch === "'" && next === "'") {
        current += "'";
        i += 1;
      } else if (ch === "'") {
        inSingle = false;
      }
      continue;
    }
    if (inDouble) {
      current += ch;
      if (ch === '"') inDouble = false;
      continue;
    }
    if (ch === "-" && next === "-") {
      current += ch;
      inLineComment = true;
      continue;
    }
    if (ch === "/" && next === "*") {
      current += ch;
      inBlockComment = true;
      continue;
    }
    if (ch === "'") {
      inSingle = true;
      current += ch;
      continue;
    }
    if (ch === '"') {
      inDouble = true;
      current += ch;
      continue;
    }
    if (ch === ";") {
      const trimmed = current.trim();
      if (trimmed) statements.push(trimmed);
      current = "";
      continue;
    }
    current += ch;
  }

  const trailing = current.trim();
  if (trailing) statements.push(trailing);
  return statements;
}

function stripSqlComments(sql: string): string {
  return sql
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/--.*$/gm, " ")
    .trim();
}

type DbCommand =
  | { type: "create_db"; name: string }
  | { type: "drop_db"; name: string }
  | { type: "create_schema"; name: string }
  | { type: "drop_schema"; name: string }
  | { type: "create_table" }
  | { type: "insert_like"; estimatedRows: number }
  | { type: "write" }
  | { type: "other" };

function unwrapIdent(raw: string): string {
  const trimmed = raw.trim();
  if (trimmed.startsWith('"') && trimmed.endsWith('"')) {
    return trimmed.slice(1, -1).toLowerCase();
  }
  return trimmed.toLowerCase();
}

function classifyStatement(raw: string): DbCommand {
  const sql = stripSqlComments(raw).replace(/\s+/g, " ");
  const upper = sql.toUpperCase();

  let match = /^CREATE\s+DATABASE\s+(?:IF\s+NOT\s+EXISTS\s+)?([a-zA-Z_][\w$]*|"[^"]+")/i.exec(sql);
  if (match) return { type: "create_db", name: unwrapIdent(match[1]) };

  match = /^DROP\s+DATABASE\s+(?:IF\s+EXISTS\s+)?([a-zA-Z_][\w$]*|"[^"]+")/i.exec(sql);
  if (match) return { type: "drop_db", name: unwrapIdent(match[1]) };

  match = /^CREATE\s+SCHEMA\s+(?:IF\s+NOT\s+EXISTS\s+)?([a-zA-Z_][\w$]*|"[^"]+")/i.exec(sql);
  if (match) return { type: "create_schema", name: unwrapIdent(match[1]) };

  match = /^DROP\s+SCHEMA\s+(?:IF\s+EXISTS\s+)?([a-zA-Z_][\w$]*|"[^"]+")/i.exec(sql);
  if (match) return { type: "drop_schema", name: unwrapIdent(match[1]) };

  if (/^CREATE\s+TABLE\b/i.test(upper)) return { type: "create_table" };

  if (/^(INSERT\s+INTO|COPY\s+)\b/i.test(upper)) {
    const valuesMatch = sql.match(/\bVALUES\s*\(/gi);
    return { type: "insert_like", estimatedRows: valuesMatch ? valuesMatch.length : 1 };
  }

  if (/^(UPDATE|DELETE|TRUNCATE)\b/i.test(upper)) return { type: "write" };

  return { type: "other" };
}

function readCourseState(): CourseState | null {
  try {
    const raw = localStorage.getItem(STATE_KEY);
    if (!raw) return null;
    const parsed = JSON.parse(raw) as Partial<CourseState>;
    if (!parsed || parsed.version !== 1) return null;
    return {
      version: 1,
      completed: parsed.completed ?? {},
      activeChapter: parsed.activeChapter ?? 0,
      activeDb: parsed.activeDb ?? COURSE_DB_NAME,
      sqlByChapter: parsed.sqlByChapter ?? {},
      parametersByChapter: parsed.parametersByChapter ?? {},
      workspaceMeta: parsed.workspaceMeta ?? {
        databases: [],
        limits: LIMITS,
        engine: "pglite-idb",
      },
      updatedAt: parsed.updatedAt ?? new Date().toISOString(),
    };
  } catch {
    return null;
  }
}

function writeCourseState(state: CourseState) {
  localStorage.setItem(STATE_KEY, JSON.stringify(state));
  const done = Object.entries(state.completed)
    .filter(([, value]) => value)
    .map(([key]) => Number(key))
    .filter((value) => Number.isFinite(value));
  localStorage.setItem("postgres-missions-completed", JSON.stringify(done));
}

function formatCell(value: unknown): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "object") return JSON.stringify(value);
  return String(value);
}

function ResultTable({ result }: { result: QueryResult }) {
  if (!result?.rows?.length) {
    return (
      <p className="m-0 text-sm text-[#9bb3b8]">
        {typeof result?.affectedRows === "number"
          ? `Statement OK · ${result.affectedRows} row(s) affected.`
          : "Statement OK · no rows returned."}
      </p>
    );
  }

  const columns = result.fields?.map((field) => field.name) ?? Object.keys(result.rows[0] ?? {});

  return (
    <div className="postgres-scroll overflow-auto">
      <table className="w-full border-collapse text-left text-xs text-[#d5eef0]">
        <thead>
          <tr>
            {columns.map((column) => (
              <th
                key={column}
                className="border-b border-[#35565f] px-2.5 py-2 font-semibold whitespace-nowrap text-[#9ad7c8]"
              >
                {column}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {result.rows.map((row, rowIndex) => (
            <tr key={`row-${rowIndex}`} className="border-t border-[#2a4b55]">
              {columns.map((column) => (
                <td key={`${rowIndex}-${column}`} className="px-2.5 py-1.5 align-top whitespace-nowrap">
                  {formatCell(row[column])}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

