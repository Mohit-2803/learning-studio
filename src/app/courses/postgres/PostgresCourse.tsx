  async function ensureCreateTableAllowed(client: PGliteClient) {
    const path = await client.query("SHOW search_path");
    const searchPath = String(path.rows?.[0]?.search_path ?? "public");
    const first = searchPath.split(",")[0]?.trim().replace(/"/g, "") || "public";
    if (first === "public" || first === "$user" || !first.startsWith(USER_SCHEMA_PREFIX)) {
      return;
    }

    const count = await client.query(
      `SELECT COUNT(*)::int AS n
       FROM information_schema.tables
       WHERE table_schema = $1 AND table_type = 'BASE TABLE'`,
      [first],
    );
    const tables = Number(count.rows?.[0]?.n ?? 0);
    if (tables >= LIMITS.maxTablesPerDatabase) {
      throw new Error(
        `Practice cap: database “${fromUserSchema(first)}” already has ${tables}/${LIMITS.maxTablesPerDatabase} tables.`,
      );
    }
  }

  async function ensureInsertAllowed(client: PGliteClient, estimatedRows: number) {
    const tables = await client.query(
      `SELECT table_schema AS schema, table_name AS table
       FROM information_schema.tables
       WHERE table_type = 'BASE TABLE' AND table_schema LIKE $1`,
      [`${USER_SCHEMA_PREFIX}%`],
    );
    let total = 0;
    for (const row of tables.rows ?? []) {
      const counted = await client.query(
        `SELECT COUNT(*)::int AS n FROM ${quoteIdent(String(row.schema))}.${quoteIdent(String(row.table))}`,
      );
      total += Number(counted.rows?.[0]?.n ?? 0);
    }
    if (total + estimatedRows > LIMITS.maxUserRowsTotal) {
      throw new Error(
        `Practice cap: at most ${LIMITS.maxUserRowsTotal} rows across your databases (currently ${total}).`,
      );
    }
  }

  async function enforcePostWriteCaps(client: PGliteClient) {
    const tables = await client.query(
      `SELECT table_schema AS schema, table_name AS table
       FROM information_schema.tables
       WHERE table_type = 'BASE TABLE' AND table_schema LIKE $1`,
      [`${USER_SCHEMA_PREFIX}%`],
    );

    let total = 0;
    for (const row of tables.rows ?? []) {
      const schema = String(row.schema);
      const table = String(row.table);
      const counted = await client.query(
        `SELECT COUNT(*)::int AS n FROM ${quoteIdent(schema)}.${quoteIdent(table)}`,
      );
      const n = Number(counted.rows?.[0]?.n ?? 0);
      total += n;
      if (n > LIMITS.maxRowsPerTable) {
        throw new Error(
          `Practice cap: ${fromUserSchema(schema)}.${table} has ${n} rows (max ${LIMITS.maxRowsPerTable}). Delete some rows to continue.`,
        );
      }
    }
    if (total > LIMITS.maxUserRowsTotal) {
      throw new Error(
        `Practice cap: ${total} total rows in your databases (max ${LIMITS.maxUserRowsTotal}). Delete some rows to continue.`,
      );
    }
  }

  async function runSql() {
    if (!db) return;
    if (sql.length > LIMITS.maxSqlChars) {
      setMessage(`Keep statements under ${LIMITS.maxSqlChars.toLocaleString()} characters in this practice lab.`);
      return;
    }

    setBusy(true);
    setMessage(null);
    setResults([]);

    try {
      const statements = splitStatements(sql);
      if (!statements.length) throw new Error("Write a SQL statement first.");

      const selected = workspace.find((item) => item.name === activeDb);
      if (selected) {
        await applyPracticeDbContext(db, selected);
      }
      const practiceName = selected?.name ?? activeDb;

      let params: unknown[] = [];
      try {
        params = JSON.parse(parameters || "[]") as unknown[];
        if (!Array.isArray(params)) throw new Error("Parameters must be a JSON array.");
      } catch {
        throw new Error('Parameters must be valid JSON array syntax, for example [3] or ["Sci-Fi"].');
      }

      const collected: QueryResult[] = [];
      let sawWrite = false;

      for (const statement of statements) {
        const runnable = rewritePracticeSql(statement, practiceName);
        const kind = classifyStatement(runnable);

        if (kind.type === "create_db" || kind.type === "create_schema") {
          const name = kind.name;
          if (!isSafeDbName(name) || name === COURSE_DB_NAME || name === "public") {
            throw new Error(`Cannot create database/schema “${name}”. Use a simple lowercase name.`);
          }
          if (workspace.some((item) => item.name === name || item.schema === name || item.schema === toUserSchema(name))) {
            throw new Error(`“${name}” already exists.`);
          }
          if (userDbCount >= LIMITS.maxUserDatabases) {
            throw new Error(`Practice cap: max ${LIMITS.maxUserDatabases} of your own databases.`);
          }
          const schema = toUserSchema(name);
          await db.exec(`CREATE SCHEMA ${quoteIdent(schema)}`);
          collected.push({
            fields: [{ name: "notice" }],
            rows: [{ notice: `Created database “${name}”.` }],
          });
          continue;
        }

        if (kind.type === "drop_db" || kind.type === "drop_schema") {
          const raw = kind.name;
          if (raw === COURSE_DB_NAME || raw === "public") {
            throw new Error("The shared course database/schema cannot be dropped.");
          }
          const name = raw.startsWith(USER_SCHEMA_PREFIX) ? fromUserSchema(raw) || raw : raw;
          const schema = raw.startsWith(USER_SCHEMA_PREFIX) ? raw : toUserSchema(name);
          await db.exec(`DROP SCHEMA IF EXISTS ${quoteIdent(schema)} CASCADE`);
          collected.push({
            fields: [{ name: "notice" }],
            rows: [{ notice: `Dropped database “${name}”.` }],
          });
          continue;
        }

        if (kind.type === "create_table") {
          await ensureCreateTableAllowed(db);
        }

        if (kind.type === "insert_like") {
          await ensureInsertAllowed(db, kind.estimatedRows);
          sawWrite = true;
        }

        if (kind.type === "write") sawWrite = true;

        if (statements.length === 1 && params.length > 0) {
          const result = await db.query(runnable, params);
          collected.push(result);
        } else {
          const execResult = await db.exec(runnable);
          if (Array.isArray(execResult)) collected.push(...execResult);
          else if (execResult) collected.push(execResult);
        }
      }

      if (sawWrite) await enforcePostWriteCaps(db);

      await refreshWorkspace(db, activeDb);
      setResults(collected);

      const validationResult = collected[collected.length - 1] ?? { rows: [] };
      const passed = chapter.check(validationResult);
      if (passed) {
        setCompleted((prev) => ({ ...prev, [active]: true }));
        setMessage(chapter.successMessage);
      } else {
        setMessage("Ran successfully. Adjust the SQL until it matches this chapter’s goal.");
      }
    } catch (error) {
      setMessage(error instanceof Error ? error.message : "Query failed.");
      try {
        if (db) await refreshWorkspace(db, activeDb);
      } catch {
        /* ignore */
      }
    } finally {
      setBusy(false);
    }
  }

