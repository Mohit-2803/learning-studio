function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/** Tokenize SQL for the dark lab editor overlay. */
function highlightSql(source: string): string {
  const tokenPattern =
    /--[^\n]*|\/\*[\s\S]*?\*\/|'(?:''|[^'])*'|"(?:""|[^"])*"|\b\d+(?:\.\d+)?\b|\b[A-Za-z_][A-Za-z0-9_]*\b|[(),.;=*<>!+\-/%]+/g;
  let html = "";
  let cursor = 0;
  for (const match of source.matchAll(tokenPattern)) {
    const token = match[0];
    const index = match.index ?? 0;
    html += escapeHtml(source.slice(cursor, index));
    let kind = "punct";
    if (token.startsWith("--") || token.startsWith("/*")) kind = "comment";
    else if (token.startsWith("'") || token.startsWith('"')) kind = "string";
    else if (/^\d/.test(token)) kind = "number";
    else if (SQL_KEYWORDS.has(token.toLowerCase())) kind = "keyword";
    else if (SQL_TYPES.has(token.toLowerCase())) kind = "type";
    else if (/^[A-Za-z_]/.test(token)) kind = "ident";
    html += `<span class="sql-tok-${kind}">${escapeHtml(token)}</span>`;
    cursor = index + token.length;
  }
  return html + escapeHtml(source.slice(cursor));
}

